"""English messages. Keys must match ja.py (checked by tests/test_domain.py).

Counts are written as "Label: n" so that singular and plural never clash.
Scores use "2 to 1" (a hyphen is read differently by each screen reader).
"""

NAME = "English"


def rank_label(n: int) -> str:
    """Rank in a table column (e.g. 3rd)."""
    if 11 <= n % 100 <= 13:
        suffix = "th"
    else:
        suffix = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def place(n: int) -> str:
    """Rank inside a sentence (e.g. 3rd place)."""
    return f"{rank_label(n)} place"


